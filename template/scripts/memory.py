#!/usr/bin/env python3
"""Validate, index and retrieve scoped repository lessons using only the standard library."""
import argparse
from datetime import date, timedelta
import json
from pathlib import Path
import re
import sys
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
STATES = {"active", "candidate", "deprecated", "superseded"}


def confined(root, rel):
    if not isinstance(rel, str) or not rel or Path(rel).is_absolute():
        raise ValueError("Expected a repository-relative file path")
    path = (root / rel).resolve()
    if not path.is_relative_to(root) or not path.is_file():
        raise ValueError(f"Missing or out-of-repository path: {rel}")
    return path


def load_lessons(root):
    data = json.loads((root / "docs/memory/lessons.json").read_text(encoding="utf-8"))
    if data.get("schema_version") != 1 or not isinstance(data.get("lessons"), list):
        raise ValueError("Expected schema_version=1 and lessons array")
    seen, paths = {}, set()
    for lesson in data["lessons"]:
        if not isinstance(lesson, dict):
            raise ValueError("Each lesson must be an object")
        for key in ("id", "title", "summary", "evidence", "path", "reviewed_on"):
            if not isinstance(lesson.get(key), str) or not lesson[key].strip():
                raise ValueError(f"Missing lesson field: {key}")
        ident = lesson["id"]
        if not re.fullmatch(r"L\d{3}", ident) or ident in seen:
            raise ValueError(f"Invalid or duplicate lesson id: {ident}")
        if lesson.get("status") not in STATES:
            raise ValueError(f"{ident}: invalid status")
        tags = lesson.get("tags")
        if not isinstance(tags, list) or not tags or not all(isinstance(t, str) and t for t in tags):
            raise ValueError(f"{ident}: tags must be a nonempty string array")
        if len(lesson["summary"]) > 350:
            raise ValueError(f"{ident}: summary exceeds 350 characters")
        date.fromisoformat(lesson["reviewed_on"])
        days = lesson.get("review_after_days")
        if days is not None and (type(days) is not int or days < 1):
            raise ValueError(f"{ident}: invalid review_after_days")
        path = confined(root, lesson["path"])
        if path in paths:
            raise ValueError(f"Duplicate lesson path: {lesson['path']}")
        paths.add(path)
        if lesson["status"] in {"deprecated", "superseded"} and not lesson.get("retirement_reason"):
            raise ValueError(f"{ident}: retirement reason required")
        seen[ident] = lesson
    for ident, lesson in seen.items():
        replacement = lesson.get("superseded_by")
        if lesson["status"] == "superseded" and not replacement:
            raise ValueError(f"{ident}: superseded_by required")
        chain = {ident}
        while replacement:
            if replacement not in seen or replacement in chain:
                raise ValueError(f"{ident}: missing or cyclic replacement")
            chain.add(replacement)
            replacement = seen[replacement].get("superseded_by")
    actual = {p.resolve() for p in (root / "docs/memory/lessons").glob("*.md")}
    if actual != paths:
        raise ValueError("Lesson registry must cover exactly the files in docs/memory/lessons")
    return list(seen.values())


def due(lesson, today):
    days = lesson.get("review_after_days")
    return days is not None and today >= date.fromisoformat(lesson["reviewed_on"]) + timedelta(days=days)


def index_text(lessons):
    lines = ["# Lesson Index", "", "Generated by `python3 scripts/memory.py index`. Edit lessons.json and the lesson body, not this index.", ""]
    for lesson in sorted(lessons, key=lambda x: x["id"]):
        rel = Path(lesson["path"]).relative_to("docs/memory").as_posix()
        lines.append(f"- [{lesson['id']} · {lesson['title']}]({rel}) | {lesson['status']} | {', '.join(lesson['tags'])} | reviewed {lesson['reviewed_on']}")
    return "\n".join(lines) + "\n"


def validate(root, lessons, today):
    errors = []
    limits = {"AGENTS.md": 8000, "docs/memory/MEMORY.md": 5000, "docs/memory/LATEST.md": 8000}
    for rel, limit in limits.items():
        text = confined(root, rel).read_text(encoding="utf-8")
        if len(text.encode("utf-8")) > limit:
            errors.append(f"{rel}: over {limit} byte budget; split by topic")
    latest = confined(root, "docs/memory/LATEST.md").read_text(encoding="utf-8")
    if not re.search(r"^Last verified: (\d{4}-\d{2}-\d{2}|not-yet-verified)$", latest, re.M):
        errors.append("LATEST.md needs Last verified: YYYY-MM-DD or not-yet-verified")
    for lesson in lessons:
        if date.fromisoformat(lesson["reviewed_on"]) > today:
            errors.append(f"{lesson['id']}: review date is in the future")
        if lesson["status"] == "active" and due(lesson, today):
            errors.append(f"{lesson['id']}: NEEDS_REVIEW; excluded from brief until revalidated")
    index = confined(root, "docs/memory/LESSONS_INDEX.md").read_text(encoding="utf-8")
    if index != index_text(lessons):
        errors.append("Lesson index drift; run scripts/memory.py index")
    # Check local Markdown file links, not external URLs or heading anchors.
    for path in sorted((root / "docs/memory").rglob("*.md")):
        for target in re.findall(r"\[[^\]]*\]\(([^)]+)\)", path.read_text(encoding="utf-8")):
            parsed = urlsplit(target.strip("<>"))
            if parsed.scheme or parsed.netloc or not parsed.path:
                continue
            dest = (path.parent / unquote(parsed.path)).resolve()
            if not dest.is_relative_to(root) or not dest.exists():
                errors.append(f"{path.relative_to(root)}: missing or external local link {target}")
    return errors


def brief(lessons, task, today, limit=5, budget=4500):
    terms = set(re.findall(r"[\w-]+", task.lower()))
    ranked, excluded = [], []
    for lesson in lessons:
        if lesson["status"] != "active" or due(lesson, today) or date.fromisoformat(lesson["reviewed_on"]) > today:
            excluded.append(lesson["id"])
            continue
        score = len(terms & {tag.lower() for tag in lesson["tags"]})
        if score or "always" in lesson["tags"]:
            ranked.append((-score, lesson["id"], lesson))
    out = "# Context Brief\n\nRead docs/memory/MEMORY.md and LATEST.md for project state.\n"
    selected = 0
    for _, _, lesson in sorted(ranked):
        block = f"\n- {lesson['id']} {lesson['title']}: {lesson['summary']}\n  Source: {lesson['path']}\n"
        if selected == limit:
            break
        # Reserve footer space; do not cut a source path in the middle.
        if len(out) + len(block) + 100 > budget:
            continue
        out += block
        selected += 1
    if not selected:
        out += "\nNo matching active lessons. Search the index or refine task tags.\n"
    footer = f"\nSelected {selected}. Candidate/retired/expired lessons excluded: {len(excluded)}.\n"
    return out + footer


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["check", "index", "brief"])
    parser.add_argument("--task", default="always")
    parser.add_argument("--limit", type=int, default=5)
    parser.add_argument("--budget", type=int, default=4500, help="Character budget, not a tokenizer estimate")
    parser.add_argument("--as-of", type=date.fromisoformat, default=date.today())
    args = parser.parse_args()
    try:
        if args.limit < 1 or args.budget < 500:
            raise ValueError("limit >= 1 and budget >= 500 are required")
        lessons = load_lessons(ROOT)
        if args.command == "index":
            path = ROOT / "docs/memory/LESSONS_INDEX.md"
            if path.is_symlink() or not path.resolve().is_relative_to(ROOT):
                raise ValueError("Index output must remain in the repository")
            with path.open("w", encoding="utf-8", newline="\n") as stream:
                stream.write(index_text(lessons))
            print("Updated lesson index")
        elif args.command == "brief":
            print(brief(lessons, args.task, args.as_of, args.limit, args.budget))
        else:
            errors = validate(ROOT, lessons, args.as_of)
            for error in errors:
                print(f"FAIL: {error}")
            if errors:
                return 1
            print(f"PASS: memory structure, index, links and review dates ({len(lessons)} lessons).")
            print("This checks structure, not whether the written claims are true.")
        return 0
    except (OSError, ValueError, TypeError, KeyError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
    sys.exit(main())
